/**
 * build-lib.mjs — inline the app into one self-contained index.html.
 *
 * Concatenation, not a bundler. The artifact has to run from file://, from a
 * sandboxed opaque-origin iframe, and with no network, which rules out
 * <script type="module" src> (module scripts are CORS-blocked on file://, and an
 * opaque origin cannot fetch siblings either). So the JavaScript must be inline,
 * and an inline classic script cannot use `import` — hence concatenating the
 * modules into one shared function scope.
 *
 * No minifier or third-party bundler is used on purpose: there are no third-party
 * dependencies to resolve, and a tool whose default invocation needs privileges
 * the checks do not have is a worse default than deterministic glue whose
 * invariants are asserted below (dependency order, no name collisions, result
 * actually parses).
 */

import { readFileSync } from 'node:fs';
import { join } from 'node:path';

/** Modules in dependency order: a file may only use names defined above it. */
const MODULES = ['acoustics.js', 'audio.js', 'app.js'];

/**
 * The embedded font faces: which weights exist and where their bytes live.
 *
 * Source of truth for the `@font-face` rules. The base64 text is generated by
 * tools/build-font.mjs and committed, so building needs neither network nor
 * font tooling. Regenerating is a deliberate act (./tools/with-fonttools.sh),
 * because a font change moves every glyph and therefore every golden screenshot.
 *
 * Two faces because the sheet asks for 600 as well as 400; shipping only the
 * Regular face lets each engine synthesise its own bold, and synthetic stem
 * weight is engine-specific.
 */
const EMBEDDED_FACES = [
  { weight: 400, file: 'StemSans-regular.woff2.base64' },
  { weight: 700, file: 'StemSans-bold.woff2.base64' },
];

/** One family for both faces, so weight matching picks between them. */
const FONT_FAMILY = 'Stem Sans';

/** Placeholder in src/styles.css that the `@font-face` rules replace. */
const FONT_FACE_TOKEN = '/* __FONT_FACE__ */';

/** The `@font-face` rules for the committed subsets, inlined into the sheet. */
function fontFaceCss(root) {
  const rules = EMBEDDED_FACES.map(({ weight, file }) => {
    const path = join(root, 'build', file);
    let base64;
    try {
      base64 = readFileSync(path, 'utf8').trim();
    } catch {
      throw new Error(`missing embedded font ${path}; generate it with ./tools/with-fonttools.sh`);
    }
    if (!/^[A-Za-z0-9+/]+={0,2}$/.test(base64)) {
      throw new Error(`${path} is not base64`);
    }
    return (
      `@font-face {\n` +
      `  font-family: "${FONT_FAMILY}";\n` +
      `  font-style: normal;\n` +
      `  font-weight: ${weight};\n` +
      `  src: url(data:font/woff2;base64,${base64}) format("woff2");\n` +
      `}`
    );
  });
  return rules.join('\n');
}

/**
 * Remove `import` statements and `export` keywords.
 *
 * Only the shapes this project uses are handled — a top-of-file
 * `import { a, b } from './x.js';` and a leading `export ` — and anything else
 * throws rather than being silently passed through, so a future edit that
 * introduces a default export or a dynamic import fails the build instead of
 * shipping a broken bundle.
 */
function stripModuleSyntax(source, name) {
  const kept = [];
  for (const line of source.split('\n')) {
    if (/^import\s+\{[^}]*\}\s+from '\.\/[^']+';?\s*$/.test(line)) continue;
    if (/^import\s/.test(line)) {
      throw new Error(`${name}: unsupported import form: ${line}`);
    }
    const exportMatch = line.match(/^export\s+(class|function|const|let)\s/);
    if (exportMatch) {
      kept.push(line.replace(/^export\s+/, ''));
      continue;
    }
    if (/^export\b/.test(line)) {
      throw new Error(`${name}: unsupported export form: ${line}`);
    }
    kept.push(line);
  }
  return kept.join('\n');
}

/**
 * Refuse a bundle in which two modules declare the same top-level name.
 *
 * Separate files make this legal; one shared scope makes the second declaration
 * throw at load time, which would present as a blank page.
 */
function assertNoTopLevelCollisions(sources) {
  const declared = new Map();
  for (const [name, source] of sources) {
    for (const match of source.matchAll(/^(?:class|function|const|let|var)\s+([A-Za-z_$][\w$]*)/gm)) {
      const symbol = match[1];
      const previous = declared.get(symbol);
      if (previous && previous !== name) {
        throw new Error(`top-level name "${symbol}" is declared in both ${previous} and ${name}`);
      }
      declared.set(symbol, name);
    }
  }
}

/** Assemble the artifact from a project root. */
export function buildArtifact(root) {
  const template = readFileSync(join(root, 'src', 'page.html'), 'utf8');
  const styles = readFileSync(join(root, 'src', 'styles.css'), 'utf8');

  const sources = MODULES.map((name) => [name, stripModuleSyntax(readFileSync(join(root, 'src', name), 'utf8'), name)]);
  assertNoTopLevelCollisions(sources);
  const bundle = sources.map(([name, source]) => `// ---- src/${name} ----\n${source}`).join('\n\n');

  const placeholderScript = /<script>\n\/\* __STEM_JS__ \*\/\n<\/script>/;
  if (!placeholderScript.test(template)) throw new Error('template is missing the script placeholder');
  const inlined = `<script>\n(function () {\n'use strict';\n\n${bundle}\n})();\n</script>`;
  const page = template
    .replace(placeholderScript, inlined)
    .replace('/* __STEM_CSS__ */', () => `${fontFaceCss(root)}\n\n${styles}`);

  if (page.includes('__STEM_JS__') || page.includes('__STEM_CSS__') || page.includes('__FONT_FACE__')) {
    throw new Error('a build placeholder survived into the artifact');
  }
  return page;
}
